// TestSchemaFieldsAreDescribed: every object and every key of the model has a description, so the generated reference
// (docs/customizing-rulesets-reference.md) leaves nothing unexplained. A new field needs an entry in fieldDocs.
func TestSchemaFieldsAreDescribed(t *testing.T) {
	root := generateSchema()
	check := func(where string, node map[string]any) {
		props, _ := node["properties"].(map[string]any)
		if len(props) > 0 {
			if d, _ := node["description"].(string); d == "" {
				t.Errorf("%s has no description: add it to typeDocs in schema_docs_test.go", where)
			}
		}
		var names []string
		for name := range props {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			if d, _ := props[name].(map[string]any)["description"].(string); d == "" {
				t.Errorf("%s.%s has no description: add %q to fieldDocs in schema_docs_test.go", where, name, where+"."+name)
			}
		}
	}
	check("Document", root)
	defs, _ := root["$defs"].(map[string]any)
	for name, d := range defs {
		if node, ok := d.(map[string]any); ok {
			check(name, node)
		}
	}
}
