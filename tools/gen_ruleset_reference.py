#!/usr/bin/env python3
"""Writes docs/customizing-rulesets-reference.md from definitions/battle_companies/battle_companies.schema.json.

The schema is generated from the Go model (internal/core/lean), and its descriptions live in
internal/core/lean/schema_docs_test.go, so this reference lists exactly what the app accepts: every object and key with its type,
whether it is required, its default, its allowed values or range, and what it means. The output is deterministic (the same schema
gives the same bytes); tools/test_ruleset_reference.py fails when the committed file is stale.

    python3 tools/gen_ruleset_reference.py            # rewrite the reference
    python3 tools/gen_ruleset_reference.py --check    # exit 1 when the committed reference is stale (what the test does)
    make ruleset-reference                            # the same, from the Makefile
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "definitions" / "battle_companies" / "battle_companies.schema.json"
OUT = ROOT / "docs" / "customizing-rulesets-reference.md"

# The value forms that read several shapes: described once, linked from the keys that use them.
FORMS_ORDER = ["Roll", "DiceSpec", "Rating", "RuleRef", "AdvanceTo", "Scalar"]

HEADER = """# Customizing rulesets: reference

<!-- Generated by tools/gen_ruleset_reference.py from definitions/battle_companies/battle_companies.schema.json. Do not edit by hand:
     change the Go model or its descriptions (internal/core/lean/schema_docs_test.go), regenerate the schema, then run `make ruleset-reference`. -->

Every object and key of the Battle Companies file (lean format, `schemaVersion` 2), as the app reads it. This page is **generated from the
schema**; the tutorial is [customizing-rulesets.md](customizing-rulesets.md), and the engine side is [definitions.md](definitions.md).

How to read the tables:

- **Required**: `yes` means the key must be present. Every other key may be left out.
- **Default**: what the app uses when the key is absent (`-` means nothing: the key adds nothing when absent).
- **Allowed**: the closed vocabulary (`a`, `b`) or the range (`1..50`) the checker enforces. A number outside its range, a word outside its
  vocabulary and a key that is not listed are all errors: an unknown key is never ignored, except in the objects marked *open* below.
- Types: `string`, `integer`, `number`, `boolean`, `list of X`, a linked object, or `any` for a section whose shape the app reads but the
  checker does not type (the description says which keys).
- The checker (`make check-ruleset`) also verifies what a schema cannot: that names resolve, that charts cover their dice, that parameters
  agree with each other. Its messages are explained in the tutorial.
"""


def anchor(name):
    return re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")


def md(text):
    """A table cell: no pipes or line breaks."""
    return str(text).replace("|", "\\|").replace("\n", " ")


class Ref:
    def __init__(self, schema):
        self.defs = schema["$defs"]
        self.forms = [f for f in FORMS_ORDER if f in self.defs]

    def name(self, ref):
        return ref.rsplit("/", 1)[-1]

    def link(self, name):
        return f"[{name}](#{anchor(name)})"

    def type_of(self, p):
        """The type column of a property."""
        if "$ref" in p:
            n = self.name(p["$ref"])
            return self.link(n) if (n in self.forms or "properties" in self.defs[n]) else n
        t = p.get("type")
        if isinstance(t, list):
            kinds = [k for k in t if k != "null"]
            base = kinds[0] if kinds else "any"
            return f"{base} or null"
        if t == "array":
            items = p.get("items", {})
            return "list of " + self.type_of(items)
        if t == "object":
            add = p.get("additionalProperties")
            if isinstance(add, dict):
                return "map of " + self.type_of(add)
            return "object"
        if t is None:
            return "any"
        return t

    def allowed(self, p):
        """The allowed column: vocabulary and range."""
        q = p.get("items", {}) if p.get("type") == "array" else p
        out = []
        if "enum" in q:
            out.append(", ".join("`null`" if e is None else f"`{e}`" for e in q["enum"]))
        if "const" in p:
            out.append(f"`{p['const']}`")
        else:
            out.append(bounds(q, "minimum", "maximum", ""))
        out.append(bounds(q, "minLength", "maxLength", " characters"))
        if p.get("type") == "array":
            out.append(bounds(p, "minItems", "maxItems", " items"))
        out = [o for o in out if o]
        return "; ".join(out) if out else "-"

    def default(self, p):
        if "default" in p:
            d = p["default"]
            return f"`{json.dumps(d)}`"
        return "-"


def bounds(q, lo, hi, unit):
    """`1..50`, `at least 1`, `at most 50`, or nothing."""
    a, b = q.get(lo), q.get(hi)
    if unit == " characters" and a == 1 and b is None:
        return "not empty"
    if unit == " characters" and a is not None:
        unit = " characters" if a != 1 else " character"
    if a is not None and b is not None:
        return f"{a}..{b}{unit}"
    if a is not None:
        return f"at least {a}{unit}"
    if b is not None:
        return f"at most {b}{unit}"
    return ""


def walk(schema, ref):
    """The object types in the order a reader meets them: the document, then depth first along each key (required keys first)."""
    order, uses = [], {}

    def keys_of(node):
        props = node.get("properties", {})
        req = [k for k in node.get("required", []) if k in props]
        return req + sorted(k for k in props if k not in req)

    def visit(node, path, tname):
        if tname in uses:
            if len(uses[tname]) < 3 and path not in uses[tname]:
                uses[tname].append(path)
            return
        uses[tname] = [path]
        order.append(tname)
        for k in keys_of(node):
            p = node["properties"][k]
            child = p
            sub = path + ("." if path else "") + k
            while True:
                if "$ref" in child:
                    n = ref.name(child["$ref"])
                    d = ref.defs[n]
                    if "properties" in d:
                        visit(d, sub, n)
                    break
                if child.get("type") == "array" and "items" in child:
                    child = child["items"]
                    sub += "[]"
                    continue
                if isinstance(child.get("additionalProperties"), dict):
                    child = child["additionalProperties"]
                    sub += ".<name>"
                    continue
                break

    visit(schema, "", "Document")
    return order, uses


def render(schema):
    ref = Ref(schema)
    order, uses = walk(schema, ref)
    out = [HEADER]

    out.append("## Contents\n")
    out.append("- [The file](#document): the top-level keys")
    out.append("- [Objects](#objects): every nested object, in the order they are met")
    out.append("- [Value forms](#value-forms): the keys that accept more than one shape (rolls, dice, ratings, rules, promotion targets)\n")

    for tname in order:
        node = schema if tname == "Document" else ref.defs[tname]
        if tname == "Document":
            out.append("## Document\n")
            out.append(node.get("description", "").strip() + "\n")
            out.append("The file is one JSON object. Its keys:\n")
        else:
            if tname == order[1]:
                out.append("## Objects\n")
            out.append(f"### {tname}\n")
            where = ", ".join(f"`{u}`" if u else "the file" for u in uses[tname])
            out.append(f"{node.get('description', '').strip()}\n")
            out.append(f"Found at: {where}.\n")
            if node.get("additionalProperties") is True:
                out.append("*Open object*: keys that are not listed are kept as they are (the app reads some of them).\n")
        props = node.get("properties", {})
        req = set(node.get("required", []))
        keys = [k for k in node.get("required", []) if k in props] + sorted(k for k in props if k not in req)
        out.append("| Key | Type | Required | Default | Allowed | Description |")
        out.append("|---|---|---|---|---|---|")
        for k in keys:
            p = props[k]
            out.append(
                f"| `{k}` | {md(ref.type_of(p))} | {'yes' if k in req else ''} | {md(ref.default(p))} | {md(ref.allowed(p))} | {md(p.get('description', ''))} |"
            )
        out.append("")

    out.append("## Value forms\n")
    out.append("These keys accept more than one shape.\n")
    for n in ref.forms:
        d = ref.defs[n]
        out.append(f"### {n}\n")
        out.append(d.get("description", "").strip() + "\n")
        alts = d.get("oneOf")
        if alts:
            out.append("Accepted forms:\n")
            for a in alts:
                out.append("- " + describe_form(a, ref))
            out.append("")
        elif d.get("type") == "string":
            out.append(f"A string matching `{d['pattern']}`.\n")
    return "\n".join(out).rstrip() + "\n"


def describe_form(a, ref):
    if "$ref" in a:
        n = ref.name(a["$ref"])
        return f"an object, see {ref.link(n)}"
    t = a.get("type")
    if t == "integer":
        rng = f" {a['minimum']}..{a['maximum']}" if "minimum" in a else ""
        return f"a whole number{rng}"
    if t == "number":
        return "a number"
    if t == "string":
        if "pattern" in a and a["pattern"] != "\\S":
            return f"a string matching `{a['pattern']}`"
        return "a non-empty string"
    if t == "array":
        return f"a list of {a.get('minItems', '')} whole numbers".replace("  ", " ")
    if t == "object":
        props = list(a.get("properties", {}))
        req = [k for k in a.get("required", []) if k in props]
        keys = req + [k for k in props if k not in req]
        names = ", ".join(f"`{k}`" for k in keys)
        if req and len(req) == len(props):
            return f"an object with the keys {names}, all required"
        return f"an object with the keys {names} (required: {', '.join(f'`{k}`' for k in req) or 'none'})"
    return json.dumps(a)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed reference differs from what the schema gives")
    ap.add_argument("--schema", default=str(SCHEMA))
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    schema = json.loads(Path(args.schema).read_text(encoding="utf-8"))
    text = render(schema)
    out = Path(args.out)
    if args.check:
        have = out.read_text(encoding="utf-8") if out.exists() else ""
        if have != text:
            print(f"{out} is stale: run `make ruleset-reference`", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
