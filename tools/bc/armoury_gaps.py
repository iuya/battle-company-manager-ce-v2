"""Wargear of the profiles that the Battle Companies Armoury does not sell (data.profileWargearNotSold) and the report of everything
that cannot be chosen or bought: the options of data.optionSales and data.reservedOptions plus this list."""
import re

from .gear import item_key


def armoury_keys(doc):
    """item_key of everything some company can buy: wargear table, equipment, any company's unique wargear, and what they are priced as."""
    bd = doc["data"]
    keys = set()
    for e in bd["wargear"]["items"]:
        keys.update(item_key(n) for n in e["names"])
    keys.update(item_key(e["name"]) for e in bd["equipment"]["items"])
    for c in bd["companies"]:
        keys.update(item_key(u["name"]) for u in c.get("uniqueWargear", []))
    for a in bd["gearAnnotations"]["items"]:
        names = [a["name"]] + a.get("aliases", [])
        if any(item_key(n) in keys for n in names):
            keys.update(item_key(n) for n in names)
        elif a.get("pricedAs") and item_key(a["pricedAs"]) in keys:
            keys.update(item_key(n) for n in names)
    return keys


def profile_wargear_not_sold(doc, van_doc, units):
    keys = armoury_keys(doc)
    by = {}
    for kind in ("heroes", "warriors"):  # the loader's order: the first occurrence wins
        for e in van_doc["data"][kind]:
            by.setdefault(e["name"], e)
    found = {}
    for u in sorted(units):
        for w in by.get(u, {}).get("wargear", []):
            if item_key(w) not in keys:
                found.setdefault(w, []).append(u)
    items = [{"item": w, "units": us} for w, us in sorted(found.items(), key=lambda kv: kv[0].lower())]
    return {"text": "Wargear that is part of a unit's vanilla profile but that no Battle Companies Armoury sells (profile armour and hand weapons, natural weapons, "
                    "the Elven cloak...). A model of the unit always starts with it (it is added on recruit) but it can never be bought, and it is not an option "
                    "to choose. Generated: every vanilla unit a company uses, every profile wargear whose item no armoury row, equipment or Unique Wargear names.",
            "items": items}


def write_report(doc, path):
    bd = doc["data"]
    L = ["# Choice of Options and Armoury gaps (generated by tools/build_battle_companies.py)", "",
         "## Options that cannot be chosen or bought", "",
         "| Unit | Option | Status | Reason |", "| --- | --- | --- | --- |"]
    seen = set()
    for i in bd["optionSales"]["items"]:
        L.append(f"| {i['unit']} | {i['option']} | {i['status']}" + (f" ({i['armouryItem']})" if i.get("armouryItem") else "") + f" | {i['reason']} |")
        seen.add((i["unit"], i["option"]))
    for i in bd["reservedOptions"]["items"]:
        if (i["unit"], i["option"]) not in seen:
            L.append(f"| {i['unit']} | {i['option']} | reserved | Army-list option of {', '.join(i['availableIn'])}; a Battle Company has no such list |")
    L += ["", "## Profile wargear no Armoury sells (added on recruit, never buyable)", "", "| Item | Units |", "| --- | --- |"]
    for i in bd["profileWargearNotSold"]["items"]:
        L.append(f"| {i['item']} | {', '.join(i['units'])} |")
    open(path, "w", encoding="utf-8").write("\n".join(L) + "\n")
